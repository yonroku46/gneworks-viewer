export function normalizeSidoName(sido: string): string {
  if (!sido) return '';
  const trimmed = sido.trim();
  return SIDO_NAME_MAP[trimmed] || trimmed;
}

export function cleanRegionName(name: string): string {
  if (!name) return '';
  return name.replace(/(소방서|센터|119안전센터|구조대|시|군|구)$/g, '').trim();
}
